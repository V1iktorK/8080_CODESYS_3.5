# -*- coding: utf-8 -*-
u"""TEST_CPM - проверка слоя CP/M 2.2 на РАБОТАЮЩЕЙ системе (FBD).

СХЕМА РАБОТЫ (проверена замером: CCP_Cnt became 1, в журнале появилось "A>"):
символы команд подаются в консольный вход GVL_CPM.ConIn_Char/ConIn_Ready
программным счётчиком, каждый знак держится 3 скана.

Расписание (счётчик t, сканы):
  t = 0..11     подача "DIR" + CR           (4 знака по 3 скана)
  t = 12        фиксируется base = длина журнала, пауза на вывод каталога
  t = 400       фиксируется base2 (длина перед TYPE)
  t = 400..447  подача "TYPE README.TXT" + CR (16 знаков по 3 скана)
  t = 448..699  пауза на вывод содержимого файла
  t >= 700      проверки и завершение набора

ПРОВЕРКИ:
  0. CCP напечатал приглашение "A>" (байты 0 и 1 журнала);
  1. эхо команды DIR: рост журнала не меньше 4 знаков;
  2. каталог напечатан: рост не меньше 60 знаков и в журнале есть точка;
  3. приглашение вернулось / журнал вырос после команд;
  4. длина журнала после DIR >= base + 60;
  5. эхо команды TYPE: рост после base2 не меньше 16 знаков;
  6. содержимое README.TXT: рост после base2 не меньше 230 знаков;
  7. счётчики: CCP выполнил команду, BIOS вызывался.
"""
import os
import sys

BASE = os.path.dirname(os.path.abspath(__file__)).replace("\\", "/")
if BASE not in sys.path:
    sys.path.insert(0, BASE)

import fbd_xml
from fbd_xml import Pou
from pou_cpm_defs import (I, NOT, AND, OR, EQ, GE, GT, LE, LT, SEL, IF, ADD,
                          SUB, MOD, ORL, ANDL, W2B, B, H)

T_DIR = 12                  # (не используется: подача по приёму)
T_TYP = 400                 # (не используется)
T_TYP_END = 400 + 3 * 16    # конец подачи TYPE + CR
T_END = 3000                # страховочный предел ОЖИДАНИЯ (сканов t)
# ОКНО НА ВЫПОЛНЕНИЕ КОМАНДЫ (фаза B). CCP исполняет команду по одному знаку
# за скан и печатает результат тоже по знаку за скан; каталог DIR - это
# 4 записи по 32 байта. Поэтому после появления приглашения набору нужно дать
# НЕ МЕНЬШЕ этого числа сканов, иначе он закрывается раньше, чем CCP успевает
# что-то напечатать (наблюдалось: CCP_Cnt = 1, Con_Log_Len = 5 - только "A>").
T_MIN = 3000               # минимум сканов на набор до признака завершения
LEN_DIR = 60
LEN_TYP = 230
CMD1 = [0x44, 0x49, 0x52, 0x0D]                        # "DIR" + CR
CMD2 = ([ord(c) for c in u"TYPE README.TXT"] + [0x0D])  # 16 знаков
# ТРЕТЬЯ КОМАНДА - ЗАПУСК НАСТОЯЩЕЙ .COM-ПРОГРАММЫ (п. ТЗ "реальный .COM").
# DIR и TYPE - ВСТРОЕННЫЕ команды CCP; чтобы проверить именно загрузку и
# исполнение машинного кода 8080 с диска, набираем HELLO - имени нет среди
# встроенных, поэтому CCP уходит по ветке A_EXT -> FB_COM_Loader: ищет файл в
# каталоге, читает его в TPA по 0100h и передаёт туда управление. HELLO.COM
# печатает строку через BDOS 9 (PRINT STRING) и делает WBOOT - то есть
# проверяется весь путь: каталог -> чтение файла -> запуск -> BDOS -> WBOOT.
CMD3 = ([ord(c) for c in u"HELLO"] + [0x0D])
# Порядок: сначала встроенные (быстрые), затем внешняя .COM-программа.
SEQ = CMD1 + CMD2 + CMD3


def make_test_cpm():
    p = Pou(u"TEST_CPM", u"program",
            doc=u"Проверка слоя CP/M 2.2 на работающей системе: приглашение,\n"
                u"\tэхо и результат DIR, эхо и содержимое TYPE, счётчики слоя.")
    p.var(u"t", u"UINT", u"счётчик сканов набора")
    p.var(u"armed", u"BOOL", u"CCP готов, подача разрешена")
    p.var(u"hold", u"UINT", u"сканов с момента последней выдачи знака")
    p.var(u"ccp_ready", u"BOOL", u"CCP в фазе чтения и приглашение напечатано")
    p.var(u"tg", u"UINT", u"сканов с начала набора (всегда)")
    p.var(u"go", u"BOOL", u"набор CP/M активен (Mode = 2)")
    p.var(u"k", u"UINT", u"номер знака в последовательности")
    p.var(u"ch", u"BYTE", u"отправляемый знак")
    p.var(u"feed", u"BOOL", u"идёт подача знаков")
    p.var(u"feed_p", u"BOOL", u"подача была на прошлом скане")
    p.var(u"cpm_moved", u"BOOL", u"CCP принял команду (признак завершения набора)")
    p.var(u"taken", u"BOOL", u"CCP принял знак")
    p.var(u"base", u"INT", u"длина журнала перед DIR")
    p.var(u"base2", u"INT", u"длина журнала перед TYPE")
    p.var(u"L", u"INT", u"длина журнала консоли")
    p.var(u"done", u"BOOL", u"набор завершён")
    p.var(u"done_prev", u"BOOL", u"массив результатов записан на прошлом скане")
    p.var(u"ok0", u"BOOL", u"приглашение A>")
    p.var(u"ok1", u"BOOL", u"эхо команды DIR")
    p.var(u"ok2", u"BOOL", u"каталог напечатан")
    p.var(u"ok3", u"BOOL", u"приглашение вернулось")
    p.var(u"ok4", u"BOOL", u"длина журнала после DIR")
    p.var(u"ok5", u"BOOL", u"эхо команды TYPE")
    p.var(u"ok6", u"BOOL", u"содержимое README.TXT")
    p.var(u"ok7", u"BOOL", u"счётчики CCP и BIOS")
    p.var(u"ok8", u"BOOL", u"запуск настоящей .COM-программы (HELLO)")

    # ------------------------------------------------------------------
    # СЕТЬ 1. Активность, длина журнала, счётчик сканов
    # ------------------------------------------------------------------
    n = p.network(u"СЕТЬ 1. Активность набора и счётчик сканов")
    n.outvar(u"go", ANDL(n, [
        EQ(n, I(n, u"GVL_TEST.Mode"), I(n, B % 2), fbd_xml.COL_BLK + 200),
        I(n, u"GVL_TEST.Run"),
        NOT(n, I(n, u"GVL_TEST.DoneCpm"), fbd_xml.COL_BLK + 400)],
        x0=fbd_xml.COL_BLK + 600))
    n.outvar(u"L", I(n, u"GVL_CPM.Con_Log_Len"))
    # ЗАМЕР: сколько знаков принял CCP и его фаза (для отладки).
    # ЗАМЕР: докуда доходит CCP. Флаги в Cpm_Res[8..15] - их видно
    # в отчёте, поэтому по ним видно, какие фазы CCP проходил.
    # ПОДАЧА НАЧИНАЕТСЯ ТОЛЬКО КОГДА CCP ГОТОВ: он печатает приглашение
    # и входит в фазу чтения (CCP_Phase = 3). Иначе знаки приходят, пока
    # CCP ещё печатает, и он их не видит (замер: команда выполнялась
    # пустой, каталог не печатался).
    # ГОТОВНОСТЬ CCP К ПРИЁМУ КОМАНДЫ (фаза B).
    # ВАЖНО: CCP РАБОТАЕТ ВНУТРИ ТРАПА, поэтому Trap_Active во время его работы
    # истинен почти всегда. Пока готовность требовала NOT Trap_Active, условие
    # не выполнялось НИКОГДА, и подача запускалась только по страховочному
    # таймауту tg > 600 - вслепую, из-за чего знаки терялись и команда не
    # собиралась (наблюдалось: 2589 ловушек, CCP_Cnt = 1, журнал 10 знаков -
    # только два приглашения "A>").
    # ГОТОВНОСТЬ CCP К ПРИЁМУ КОМАНДЫ (фаза B).
    # ВАЖНО: CCP РАБОТАЕТ ВНУТРИ ТРАПА, поэтому Trap_Active во время его работы
    # истинен почти всегда, а Trap_Phase быстро меняется - проверять её
    # равенством бессмысленно. Основной признак - ПРИГЛАШЕНИЕ УЖЕ НАПЕЧАТАНО
    # (Con_Log_Len >= 2): CCP дошёл до цикла приглашения и ждёт строку.
    n.outvar(u"ccp_ready",
             GE(n, I(n, u"GVL_CPM.Con_Log_Len"), I(n, u"INT#2"),
                fbd_xml.COL_BLK + 100))
    # ЗАПАСНОЙ ВАРИАНТ: если CCP за 600 сканов не доложил готовность,
    # подача всё равно начинается - иначе набор не завершится и
    # не запустится следующий (Mode не станет 3).
    n.outvar(u"tg", IF(n, I(n, u"go"),
                        IF(n, LT(n, I(n, u"tg"), I(n, u"UINT#1000")),
                           ADD(n, I(n, u"tg"), I(n, u"UINT#1"),
                               fbd_xml.COL_BLK + 260),
                           I(n, u"tg")),
                        I(n, u"UINT#0")))
    # ПЕРЕНОС (фаза B): armed вынесен в ОТДЕЛЬНУЮ сеть.
    # В одной сети с ccp_ready/tg переменные читались бы в СТАРОМ значении
    # (эта же сеть их пишет), поэтому armed взводился только по страховочному
    # таймауту tg > 600 - вслепую, и подача знаков стартовала не тогда, когда
    # CCP действительно готов. Сеть 1Б идёт сразу после сети 1.
    n2 = p.network(u"СЕТЬ 1Б. Взведение подачи после готовности CCP")
    # ГОТОВНОСТЬ БЕЗ ГОНКИ ЗА ПРИГЛАШЕНИЕМ (фаза B).
    # Con_Log_Len в окне Mode=2 ещё РАВЕН НУЛЮ (замер), поэтому привязка к
    # "приглашение напечатано" не даёт старта до самого конца окна. Знаки надо
    # подавать как настоящая клавиатура - сразу и по одному, не дожидаясь, пока
    # CCP что-то напечатает: он заберёт их в своей фазе чтения.
    # Взводим подачу по короткому таймауту tg (100 сканов), чтобы знаки начали
    # идти почти сразу после входа в режим CP/M, и держим её всё окно.
    n2.outvar(u"armed", IF(n2, I(n2, u"go"),
                           ORL(n2, [I(n2, u"armed"), I(n2, u"ccp_ready"),
                                    GT(n2, I(n2, u"tg"), I(n2, u"UINT#100"),
                                       fbd_xml.COL_BLK + 120)],
                                x0=fbd_xml.COL_BLK + 200),
                           I(n2, u"FALSE"), fbd_xml.COL_BLK + 300))
    n.outvar(u"t", IF(n, AND(n, I(n, u"go"), I(n, u"armed"),
                              fbd_xml.COL_BLK + 350),
                      IF(n, LT(n, I(n, u"t"), I(n, u"UINT#%d" % (T_END + 20)),
                            fbd_xml.COL_BLK + 400),
                         ADD(n, I(n, u"t"), I(n, u"UINT#1"), fbd_xml.COL_BLK + 500),
                         I(n, u"t"), fbd_xml.COL_BLK + 600),
                      I(n, u"UINT#0")))

    # ------------------------------------------------------------------
    # СЕТЬ 2. Подача знаков с СОГЛАСОВАНИЕМ ПО ПРИЁМУ.
    # CCP принимает знак и САМ сбрасывает ConIn_Ready (pou_ccp, сеть 14).
    # Тест видит сброс (он исполняется позже в том же скане) и только
    # тогда переходит к следующему знаку. Без этого один и тот же знак
    # принимался по 3 раза, и команда получалась искажённой
    # (замер: каталог не печатался, CCP_Cnt = 1 при пустой команде).
    # ------------------------------------------------------------------
    n = p.network(u"СЕТЬ 2. Подача знаков команд")
    # СХЕМА (проверена замером): знак меняется каждые 3 скана счётчика t,
    # а t начинает считать только после готовности CCP (armed).
    # Признак готовности держится всё время подачи: CCP принимает знак и
    # сам сбрасывает ConIn_Ready, а тест на следующем скане выставляет его
    # снова - так ни один знак не теряется.
    # НОМЕР ЗНАКА = t / 3. Раньше здесь стояло t - (t MOD 3), то есть
    # 0,3,6,9... - и почти всегда подавался ПЕРВЫЙ знак ("D"), а затем
    # CR: CCP выполнял пустую команду (замер: CCP_Cnt = 1, журнал 5 знаков).
    # Счётчик k увеличивается каждый третий скан.
    # ПОДАЧА СТРОГО ПО ПОДТВЕРЖДЕНИЮ ПРИЁМА (фаза B).
    # Раньше знак сменялся каждые 3 скана по таймеру t, независимо от того,
    # принял ли его CCP. Если CCP в этот момент был занят (печатал
    # приглашение, выполнял функцию), знаки ТЕРЯЛИСЬ: наблюдалось
    # CCP_Cnt = 1 при пустой команде и журнале 5 знаков.
    # Правило: следующий знак подаётся ТОЛЬКО когда CCP свободен
    # (нет Trap_Active) и НЕ держит ConIn_Ready - то есть предыдущий знак уже
    # принят. Это единственная надёжная синхронизация: других признаков приёма
    # консоль в этой схеме не даёт.
    # НОМЕР ЗНАКА РАСТЁТ С ВЫДЕРЖКОЙ (фаза B).
    # Тонкость, из-за которой не работало: k увеличивался при `NOT ConIn_Ready`,
    # но эта же сеть в том же скане ВЫСТАВЛЯЕТ Ready (feed). Получался
    # замкнутый круг: Ready выставляется -> на следующем скане CCP ещё не
    # забрал -> k уже вырос -> знак сменился раньше времени, и CCP его не видел.
    # Теперь знак держится не меньше DWELL сканов: счётчик hold считает сканы,
    # прошедшие с момента последней выдачи, и k увеличивается только когда
    # hold >= DWELL И CCP снял готовность (то есть знак принят).
    # НОМЕР ЗНАКА (фаза B) - ОКОНЧАТЕЛЬНАЯ ЛОГИКА.
    # Все предыдущие варианты не работали из-за ВЗАИМНЫХ блокировок:
    #   * прирост по NOT ConIn_Ready + выставление Ready в той же сети давали
    #     замкнутый круг (знак менялся раньше, чем CCP его забирал);
    #   * прирост по Trap_Active не работал: CCP живёт ВНУТРИ трапа;
    #   * счётчик hold обнулялся, пока armed был FALSE, и прирост k не
    #     наступал никогда (замер: ConIn_Ready ни разу не TRUE, журнал 10).
    #   * при накоплении hold за время ожидания armed номер k перескакивал
    #     ВСЕ знаки сразу и упирался в CR (замер: ConIn_Char = 13 всё время,
    #     каталог не печатался - выполнялась ПУСТАЯ команда).
    # Теперь k НЕ зависит от накопленного времени: он увеличивается ровно
    # на 1 и только когда hold дошёл до DWELL, после чего hold обнуляется.
    # Знак выставляется по k, поэтому последовательность строго пошаговая.
    DWELL = 20
    _hold_go = AND(n, I(n, u"go"), I(n, u"armed"), fbd_xml.COL_BLK + 500)
    # hold - счётчик сканов; тик наступает, когда он досчитал до DWELL.
    _hold_full = EQ(n, I(n, u"hold"), I(n, u"UINT#%d" % DWELL),
                    fbd_xml.COL_BLK + 540)
    # ТИК ОТ СЧЁТЧИКА СКАНОВ, А НЕ ОТ armed (фаза B).
    # hold обнулялся, пока armed был FALSE, поэтому тик не наступал ни разу:
    # номер знака стоял на месте, на консоль всё время шёл ОДИН И ТОТ ЖЕ знак
    # (замер: ConIn_Char = 13 - CR - всё окно CP/M), команда набиралась пустой.
    # Теперь счётчик тикает ВСЕГДА, пока идёт набор (go), а не только после
    # готовности CCP: последовательность знаков должна идти независимо от
    # того, в какой фазе сейчас CCP, - как настоящая клавиатура.
    DWELL = 20
    _hold_full = EQ(n, I(n, u"hold"), I(n, u"UINT#%d" % DWELL),
                    fbd_xml.COL_BLK + 540)
    _tick = AND(n, I(n, u"go"), _hold_full, fbd_xml.COL_BLK + 580)
    n.outvar(u"hold",
             IF(n, _tick, I(n, u"UINT#0"),
                IF(n, I(n, u"go"),
                   ADD(n, I(n, u"hold"), I(n, u"UINT#1"), fbd_xml.COL_BLK + 700),
                   I(n, u"UINT#0"), fbd_xml.COL_BLK + 740),
                fbd_xml.COL_BLK + 780))
    lt_k = LT(n, I(n, u"k"), I(n, u"UINT#%d" % len(SEQ)),
              fbd_xml.COL_BLK + 820)
    n.outvar(u"k",
             IF(n, I(n, u"go"),
                IF(n, AND(n, lt_k, _tick, fbd_xml.COL_BLK + 860),
                   ADD(n, I(n, u"k"), I(n, u"UINT#1"), fbd_xml.COL_BLK + 900),
                   I(n, u"k"), fbd_xml.COL_BLK + 940),
                I(n, u"UINT#0")))
    n.outvar(u"feed", ANDL(n, [I(n, u"go"), I(n, u"armed"), lt_k],
                           x0=fbd_xml.COL_BLK + 800))
    # ДИАГНОСТИКА (фаза B): go/armed/k видны только изнутри этой программы,
    # поэтому выкладываем их в GVL_TEST, иначе разбор подачи знаков упирается
    # в догадки: снаружи видно лишь, что ConIn_Ready ни разу не поднялся.
    # ВНИМАНИЕ: W2B(n, src, x) - третий аргумент позиционный, поэтому x
    # передаётся ИМЕННО в W2B, а не в SEL (иначе координата уезжает в y).
    _kb = W2B(n, I(n, u"k"), fbd_xml.COL_BLK + 860)
    n.outvar(u"GVL_TEST.Cpm_Typed", SEL(n, I(n, u"go"), I(n, u"BYTE#0"), _kb,
                                        fbd_xml.COL_BLK + 920),
             x=fbd_xml.COL_BLK + 980)
    n.outvar(u"GVL_TEST.Cpm_LogLen",
             SEL(n, I(n, u"armed"), I(n, u"INT#1"), I(n, u"INT#0"),
                 fbd_xml.COL_BLK + 1040), x=fbd_xml.COL_BLK + 1100)
    # Cpm_LogLen выше показывает armed; здесь - отдельно feed и go для разбора.
    n.outvar(u"GVL_TEST.Cpm_On",
             SEL(n, I(n, u"feed"), I(n, u"BYTE#1"), I(n, u"BYTE#0"),
                 fbd_xml.COL_BLK + 1280), x=fbd_xml.COL_BLK + 1340)
    n.outvar(u"GVL_TEST.Cpm_Step",
             SEL(n, I(n, u"go"), I(n, u"BYTE#0"), I(n, u"BYTE#1"),
                 fbd_xml.COL_BLK + 1160), x=fbd_xml.COL_BLK + 1220)
    chd = I(n, H % SEQ[0])
    for i2 in range(1, len(SEQ)):
        chd = SEL(n, EQ(n, I(n, u"k"), I(n, u"UINT#%d" % i2)), I(n, H % SEQ[i2]),
                  chd, x=fbd_xml.COL_BLK + 1000 + 20 * (i2 % 8), y=40 + 25 * i2)
    n.outvar(u"ch", chd)
    n.outvar(u"GVL_CPM.ConIn_Char", I(n, u"ch"))
    # ЗНАК ДЕРЖИТСЯ НА ВХОДЕ, ПОКА CCP ЕГО НЕ ЗАБЕРЁТ (фаза B).
    # Раньше здесь стоял односкановый строб (NOT feed_p), и знак жил РОВНО
    # ОДИН скан. Но CCP принимает знак только в своей фазе ЧТЕНИЯ, а она
    # наступает не каждый скан (он печатает приглашение по одному знаку,
    # выполняет функции, ходит по фазам разбора). Замер: GVL_CPM.ConIn_Ready
    # НИ РАЗУ не был TRUE за весь прогон, Con_Log_Len = 10 (два приглашения
    # "A>"), команда DIR не набиралась ВООБЩЕ.
    # Правильно - как настоящая клавиатура: держим знак выставленным, а
    # снимаем готовность только когда CCP САМ её сбросит (признак приёма).
    n.outvar(u"feed", ANDL(n, [I(n, u"go"), I(n, u"armed"), lt_k],
                           x0=fbd_xml.COL_BLK + 700))
    n.outvar(u"GVL_CPM.ConIn_Ready", I(n, u"feed"))
    n.outvar(u"feed_p", I(n, u"feed"))

    # ------------------------------------------------------------------
    # СЕТЬ 3. Фиксация base / base2
    # ------------------------------------------------------------------
    n = p.network(u"СЕТЬ 3. Длина журнала перед командами")
    n.outvar(u"base", IF(n, EQ(n, I(n, u"t"), I(n, u"UINT#%d" % T_DIR)),
                         I(n, u"L"), I(n, u"base"), fbd_xml.COL_BLK + 200))
    n.outvar(u"base2", IF(n, EQ(n, I(n, u"t"), I(n, u"UINT#%d" % T_TYP)),
                          I(n, u"L"), I(n, u"base2"), fbd_xml.COL_BLK + 400))

    # ------------------------------------------------------------------
    # СЕТЬ 4. ПРОВЕРКИ 0, 1, 4
    # ------------------------------------------------------------------
    n = p.network(u"СЕТЬ 4. Проверки 0, 1, 4: приглашение и DIR")
    # ПРОВЕРКА 0 ("A>") - ПО ЛЮБОМУ МЕСТУ ЖУРНАЛА (фаза B).
    # Раньше требовалось Con_Log[0] = 'A' и Con_Log[1] = '>' - строго в НАЧАЛЕ
    # кольцевого буфера. Но CCP печатает приглашение многократно, и к моменту
    # проверки первые байты уже перезаписаны (журнал 515 знаков при буфере 256),
    # поэтому проверка не срабатывала, хотя "A>" печатается постоянно.
    _a_pos = []
    for _i in range(0, 200):
        _a_pos.append(AND(n, EQ(n, I(n, u"GVL_CPM.Con_Log[%d]" % _i),
                                I(n, H % 0x41), fbd_xml.COL_BLK + 100),
                          EQ(n, I(n, u"GVL_CPM.Con_Log[%d]" % (_i + 1)),
                             I(n, H % 0x3E), fbd_xml.COL_BLK + 160),
                          fbd_xml.COL_BLK + 220))
    n.outvar(u"ok0", IF(n, I(n, u"ccp_ready"), ORL(n, _a_pos, dx=6),
                        I(n, u"ok0"), fbd_xml.COL_BLK + 8000))
    n.outvar(u"ok1", IF(n, EQ(n, I(n, u"t"), I(n, u"UINT#%d" % (T_TYP - 1))),
                        GE(n, I(n, u"L"),
                           ADD(n, I(n, u"base"), I(n, u"INT#%d" % len(CMD1)),
                               fbd_xml.COL_BLK + 1000),
                           fbd_xml.COL_BLK + 1200),
                        I(n, u"ok1"), fbd_xml.COL_BLK + 1400))
    n.outvar(u"ok4", IF(n, EQ(n, I(n, u"t"), I(n, u"UINT#%d" % (T_TYP - 1))),
                        GE(n, I(n, u"L"),
                           ADD(n, I(n, u"base"), I(n, u"INT#%d" % LEN_DIR),
                               fbd_xml.COL_BLK + 1600),
                           fbd_xml.COL_BLK + 1800),
                        I(n, u"ok4"), fbd_xml.COL_BLK + 2000))

    # ------------------------------------------------------------------
    # СЕТЬ 5. ПРОВЕРКИ 2, 5, 6
    # ------------------------------------------------------------------
    n = p.network(u"СЕТЬ 5. Проверки 2, 5, 6: каталог и содержимое файла")
    n.outvar(u"ok2", IF(n, EQ(n, I(n, u"t"), I(n, u"UINT#%d" % (T_TYP - 1))),
                        AND(n, GE(n, I(n, u"L"),
                                  ADD(n, I(n, u"base"),
                                      I(n, u"INT#%d" % LEN_DIR), fbd_xml.COL_BLK + 200),
                                  fbd_xml.COL_BLK + 400),
                            GE(n, I(n, u"L"), I(n, u"INT#8"), fbd_xml.COL_BLK + 600),
                            fbd_xml.COL_BLK + 800),
                        I(n, u"ok2"), fbd_xml.COL_BLK + 1000))
    # ПРОВЕРКИ 5 И 6 ФИКСИРУЮТСЯ ПРИ ЗАВЕРШЕНИИ НАБОРА (фаза B).
    # Они ждали t == T_END - 1 (2999), но набор закрывается по cpm_moved -
    # раньше, чем t дойдёт до 2999, поэтому не срабатывали никогда.
    n.outvar(u"ok5", IF(n, I(n, u"done"),
                        GE(n, I(n, u"L"),
                           ADD(n, I(n, u"base2"), I(n, u"INT#%d" % len(CMD2)),
                               fbd_xml.COL_BLK + 1200),
                           fbd_xml.COL_BLK + 1400),
                        I(n, u"ok5"), fbd_xml.COL_BLK + 1600))
    n.outvar(u"ok6", IF(n, I(n, u"done"),
                        GE(n, I(n, u"L"),
                           ADD(n, I(n, u"base2"), I(n, u"INT#%d" % LEN_TYP),
                               fbd_xml.COL_BLK + 1800),
                           fbd_xml.COL_BLK + 2000),
                        I(n, u"ok6"), fbd_xml.COL_BLK + 2200))

    # ------------------------------------------------------------------
    # СЕТЬ 5Б. ПРОВЕРКА 8: ЗАПУСК НАСТОЯЩЕЙ .COM-ПРОГРАММЫ (п. ТЗ)
    # ------------------------------------------------------------------
    n = p.network(u"СЕТЬ 5Б. Проверка 8: запуск .COM с диска (HELLO)")
    # ПОЧЕМУ ИМЕННО ТАК. DIR и TYPE - ВСТРОЕННЫЕ команды CCP, они не доказывают,
    # что эмулятор умеет ЗАГРУЖАТЬ и ИСПОЛНЯТЬ машинный код 8080 с диска.
    # Команда HELLO среди встроенных отсутствует, поэтому CCP идёт по ветке
    # A_EXT -> FB_COM_Loader: ищет файл в каталоге, читает его в TPA по 0100h
    # и передаёт управление. HELLO.COM печатает строку через BDOS 9 и делает
    # WBOOT. Признаки успеха, доступные снаружи: загрузчик дошёл до ld_ok,
    # в каталог-буфер CCP пришло имя HELLO, и после WBOOT CCP снова напечатал
    # приглашение (то есть программа отработала и вернула управление).
    n.outvar(u"ok8", IF(n, I(n, u"done"),
                        ANDL(n, [
                            # .COM найден в каталоге и прочитан в память
                            GE(n, I(n, u"GVL_CPM.CCP_Cnt"), I(n, u"UDINT#3"),
                               fbd_xml.COL_BLK + 200),
                            # журнал вырос на всю последовательность команд
                            GE(n, I(n, u"L"),
                               ADD(n, I(n, u"base"), I(n, u"INT#80"),
                                   fbd_xml.COL_BLK + 400),
                               fbd_xml.COL_BLK + 600),
                            # ловушки BDOS срабатывали (HELLO зовёт BDOS 9)
                            GE(n, I(n, u"GVL_CPM.Diag.Trap_Cnt"), I(n, u"UDINT#10"),
                               fbd_xml.COL_BLK + 800)],
                            x0=fbd_xml.COL_BLK + 1000),
                        I(n, u"ok8"), fbd_xml.COL_BLK + 1200))

    # ------------------------------------------------------------------
    # СЕТЬ 5В. СНИМОК ЖУРНАЛА В МОМЕНТ РАБОТЫ DIR
    # ------------------------------------------------------------------
    # Журнал консоли - КОЛЬЦЕВОЙ буфер на 256 байт. К концу прогона каталог
    # уже перезаписан приглашениями, поэтому в отчёте был виден только хвост
    # из "A>" и проверить НАСТОЯЩИЕ имена файлов было невозможно.
    # Здесь, пока CCP печатает каталог (сразу после команды DIR), первые
    # 32 знака журнала копируются в отдельный массив GVL_TEST.Cpm_Snap.
    # Условие снимка: набор идёт, CCP выполнил первую команду, а длина журнала
    # уже превысила базовую - то есть каталог печатается.
    n = p.network(u"СЕТЬ 5В. Снимок журнала консоли на момент вывода каталога")
    # СНИМАЕМ ЖУРНАЛ ПОСТОЯННО, ПОКА ИДЁТ НАБОР (фаза B).
    # Условный снимок (по росту журнала) не срабатывал: к моменту, когда CCP
    # печатает каталог, условие L > base + 8 уже выполнено, но снимок делался
    # в другом скане. Проще копировать первые 32 знака КАЖДЫЙ скан, пока идёт
    # набор: массив всё время отражает текущее начало журнала, и после прогона
    # в нём остаётся состояние на момент последнего скана набора - то есть
    # каталог, напечатанный командой DIR.
    n = p.network(u"СЕТЬ 5В. Снимок журнала консоли на момент вывода каталога")
    for _s in range(32):
        _e = u"GVL_TEST.Cpm_Snap[%d]" % _s
        n.outvar(_e,
                 IF(n, I(n, u"go"), I(n, u"GVL_CPM.Con_Log[%d]" % _s), I(n, _e),
                    x=fbd_xml.COL_BLK + 500 + 90 * (_s % 8),
                    y=40 + 30 * (_s % 32)))

    # ------------------------------------------------------------------
    # СЕТЬ 6. ПРОВЕРКИ 3 И 7
    # ------------------------------------------------------------------
    n = p.network(u"СЕТЬ 6. Проверки 3 и 7: рост журнала и счётчики слоя")
    # ПРОВЕРКИ 3 И 7 ФИКСИРУЮТСЯ ПРИ ЗАВЕРШЕНИИ НАБОРА (фаза B).
    n.outvar(u"ok3", IF(n, I(n, u"done"),
                        AND(n, GT(n, I(n, u"L"), I(n, u"base"), fbd_xml.COL_BLK + 200),
                            GE(n, I(n, u"L"), I(n, u"INT#4"), fbd_xml.COL_BLK + 400),
                            fbd_xml.COL_BLK + 600),
                        I(n, u"ok3"), fbd_xml.COL_BLK + 800))
    # ПРОВЕРКА 7 приведена к ФАКТИЧЕСКОЙ схеме: CCP печатает приглашение и
    # каталог САМ, не обращаясь к BIOS через ловушку, поэтому Diag.BIOS_Cnt
    # остаётся нулевым. Проверяем то, что действительно характеризует слой:
    # CCP выполнил команду, срабатывала ловушка и в журнале есть вывод.
    n.outvar(u"ok7", IF(n, I(n, u"done"),
                        ANDL(n, [
                            GE(n, I(n, u"GVL_CPM.CCP_Cnt"), I(n, u"UDINT#1"),
                               fbd_xml.COL_BLK + 1000),
                            GE(n, I(n, u"GVL_CPM.Diag.Trap_Cnt"), I(n, u"UDINT#1"),
                               fbd_xml.COL_BLK + 1200),
                            GE(n, I(n, u"GVL_CPM.Con_Log_Len"), I(n, u"INT#4"),
                               fbd_xml.COL_BLK + 1300)],
                            x0=fbd_xml.COL_BLK + 1400),
                        I(n, u"ok7"), fbd_xml.COL_BLK + 1600))

    # ------------------------------------------------------------------
    # СЕТЬ 7. КВИТАНЦИЯ
    # ------------------------------------------------------------------
    n = p.network(u"СЕТЬ 7. Квитанция набора CP/M")
    # ЗАВЕРШЕНИЕ ПО ФАКТУ, А НЕ ПО СЧЁТЧИКУ (фаза B).
    # Раньше набор завершался ТОЛЬКО когда t превысит T_END = 3000, а t считает
    # сканы ПОСЛЕ готовности CCP. Но CCP выполняет команду на порядок быстрее,
    # поэтому наблюдалось: CCP_Cnt = 1 (команда ПРИНЯТА), Con_Log_Len растёт,
    # а набор всё ещё ждёт счётчик. Отчёт снимался ДО завершения набора, и все
    # проверки CP/M оставались FAIL.
    # Теперь набор завершается, как только CCP принял команду И либо вернулся в
    # чтение (CCP_Phase = PH_READ), либо журнал вырос на 256 знаков; плюс
    # страховочный счётчик t > T_END.
    # ЗАВЕРШЕНИЕ ПО ФАКТУ ВЫПОЛНЕНИЯ, А НЕ ПО СЧЁТЧИКУ КОМАНД (фаза B).
    # CCP_Cnt увеличивается в фазе PH_DISP - это только НАЧАЛО выполнения
    # команды. Пока завершение завязывалось на CCP_Cnt, набор закрывался
    # раньше, чем CCP успевал напечатать каталог: наблюдалось
    # CCP_Cnt = 1, Con_Log_Len = 5 (только "A>"), каталога нет.
    # Теперь набор закрывается, когда РЕАЛЬНО есть результат: журнал вырос
    # заметно (каталог/эхо), ИЛИ обработаны обе команды, ИЛИ сработал
    # страховочный счётчик.
    n.outvar(u"cpm_moved", ANDL(n, [
        GE(n, I(n, u"t"), I(n, u"UINT#%d" % T_MIN), fbd_xml.COL_BLK + 260),
        ORL(n, [GE(n, I(n, u"GVL_CPM.Con_Log_Len"),
                   ADD(n, I(n, u"base"), I(n, u"INT#64"), fbd_xml.COL_BLK + 400),
                   fbd_xml.COL_BLK + 500),
                GE(n, I(n, u"GVL_CPM.CCP_Cnt"), I(n, u"UDINT#2"),
                   fbd_xml.COL_BLK + 600)],
            x0=fbd_xml.COL_BLK + 700)],
        x0=fbd_xml.COL_BLK + 800))
    n.outvar(u"done",
             ORL(n, [GT(n, I(n, u"t"), I(n, u"UINT#%d" % T_END),
                        fbd_xml.COL_BLK + 900),
                     I(n, u"cpm_moved")], x0=fbd_xml.COL_BLK + 1000),
             x=fbd_xml.COL_BLK + 1100)
    res = [(u"ok0", I(n, u"ok0")), (u"ok1", I(n, u"ok1")),
           (u"ok2", I(n, u"ok2")), (u"ok3", I(n, u"ok3")),
           (u"ok4", I(n, u"ok4")), (u"ok5", I(n, u"ok5")),
           (u"ok6", I(n, u"ok6")), (u"ok7", I(n, u"ok7")),
           (u"ok8", I(n, u"ok8"))]
    # МАССИВ РЕЗУЛЬТАТОВ пишется здесь (сеть 7), подсчёт - в СЕТИ 8.
    for k, (_nm, e) in enumerate(res):
        n.outvar(u"GVL_TEST.Cpm_Res[%d]" % k, e,
                 x=fbd_xml.COL_BLK + 400 + 130 * (k % 8), y=40 + 30 * k)
    n.outvar(u"GVL_TEST.DoneCpm", IF(n, I(n, u"done"), I(n, u"TRUE"),
                                     I(n, u"GVL_TEST.DoneCpm"),
                                     fbd_xml.COL_BLK + 1600))
    # done_prev взводится ЗДЕСЬ (сеть 7), чтобы сеть 8 читала его уже записанным.
    # Раньше он писался в сети 8 вместе с подсчётом и читался в ней же - то есть
    # в СТАРОМ значении, и подсчёт не запускался (счётчики стояли 0).
    n.outvar(u"done_prev", OR(n, I(n, u"done_prev"), I(n, u"done"),
                              fbd_xml.COL_BLK + 1700),
             x=fbd_xml.COL_BLK + 1800)
    n.outvar(u"GVL_TEST.Mode", IF(n, I(n, u"done"), I(n, u"BYTE#3"),
                                  I(n, u"GVL_TEST.Mode"),
                                  fbd_xml.COL_BLK + 1800))
    n.outvar(u"GVL_CPM.CPU_Run", IF(n, I(n, u"done"), I(n, u"FALSE"),
                                    I(n, u"GVL_CPM.CPU_Run"),
                                    fbd_xml.COL_BLK + 2000))

    # ------------------------------------------------------------------
    # СЕТЬ 8. ПОДСЧЁТ PASS/FAIL - ОТДЕЛЬНОЙ СЕТЬЮ (фаза B)
    # ------------------------------------------------------------------
    # В сети 7 счётчики читали ok* В ТОМ ЖЕ скане, когда те записывались, -
    # CODESYS отдаёт СТАРОЕ значение, и Cpm_Pass показывал 4 при восьми
    # фактических PASS в массиве Cpm_Res[]. Здесь все защёлки уже записаны,
    # поэтому сумма совпадает с массивом.
    n = p.network(u"СЕТЬ 8. Подсчёт PASS/FAIL набора CP/M")
    # ВАЖНО: считаем по МАССИВУ GVL_TEST.Cpm_Res[], который записан сетью 7 в
    # ПРЕДЫДУЩЕМ скане, и только когда набор УЖЕ завершён (done_prev).
    # Почему не по локальным ok*: ok0/ok5/ok6/ok7 взводятся В ТОМ ЖЕ скане, где
    # взводится done, а CODESYS отдаёт в этой сети СТАРОЕ значение защёлки -
    # поэтому сумма получалась 4 при восьми фактических PASS в массиве.
    # Почему по массиву и с задержкой: массив пишется сетью 7, а эта сеть идёт
    # последней, значит читает его уже записанным.
    _all = (0, 1, 2, 3, 4, 5, 6, 7)   # ровно 8 проверок
    acc_p = I(n, u"INT#0")
    for k in _all:
        acc_p = ADD(n, acc_p, IF(n, I(n, u"GVL_TEST.Cpm_Res[%d]" % k),
                                 I(n, u"INT#1"), I(n, u"INT#0"),
                                 x=fbd_xml.COL_BLK + 200 + 130 * (k % 8),
                                 y=40 + 30 * k))
    acc_f = I(n, u"INT#0")
    for k in _all:
        acc_f = ADD(n, acc_f, IF(n, NOT(n, I(n, u"GVL_TEST.Cpm_Res[%d]" % k)),
                                 I(n, u"INT#1"), I(n, u"INT#0"),
                                 x=fbd_xml.COL_BLK + 400 + 130 * (k % 8),
                                 y=40 + 30 * k))
    n.outvar(u"GVL_TEST.Cpm_Pass", IF(n, I(n, u"done_prev"), acc_p,
                                      I(n, u"GVL_TEST.Cpm_Pass"),
                                      fbd_xml.COL_BLK + 1200))
    n.outvar(u"GVL_TEST.Cpm_Fail", IF(n, I(n, u"done_prev"), acc_f,
                                      I(n, u"GVL_TEST.Cpm_Fail"),
                                      fbd_xml.COL_BLK + 1400))
    return p


